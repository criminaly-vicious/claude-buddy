import atlasUrl from "./sprites/buddy/atlas.png";
import { HitRegionSync } from "./overlay/hitSync";
import { RenderLoop } from "./overlay/loop";
import { activeLayout, flightArea, homeArea } from "./overlay/expand";
import { balloonLines, HoverState, miniBalloonLines, placeCard, Rect } from "./overlay/hoverCard";
import { MINI_BOX, parseMiniKey } from "./overlay/minis";
import {
  expandOverlay,
  ExpandedLayout,
  ExpandMode,
  focusSession,
  getOverlayAnchor,
  HitRegion,
  onOverlayAnchor,
  onOverlayPointer,
  onOverlayVisible,
  restoreOverlay,
  setHitRegions,
  setOverlayContentSize,
} from "./overlay/native";
import {
  BALLOON_MAX_HEIGHT,
  BALLOON_MAX_WIDTH,
  drawBalloon,
  drawScene,
  measureBalloon,
  TAIL_ROWS,
} from "./overlay/renderer";
import { CONTROLLER_CLIPS } from "./overlay/controller";
import { BODY_BOX, DEFAULT_STROLLS, Scene, StrollTiming, Viewport } from "./overlay/scene";
import { subscribeSessions } from "./overlay/sessions";

/** Every animation the overlay plays; the atlas must have them all. */
const OVERLAY_CLIPS = [
  ...CONTROLLER_CLIPS,
  "walk_left",
  "walk_right",
  "mini_work",
  "mini_balance",
  "mini_pop",
  "mini_poof",
  "mini_fly",
  "mini_land",
  "mini_jump",
  "mini_walk_left",
  "mini_walk_right",
  "talk",
  "fx_talk",
  "fx_reply",
  "grabbed",
  "fly",
  "land",
  "land_splat",
  "dizzy",
];
/** The `+N` group collapses this long after the pointer leaves it. */
const COLLAPSE_AFTER_MS = 1500;
/** A press that moves further than this (CSS pixels) is a drag, not a click. */
const DRAG_THRESHOLD = 4;
/**
 * When the backend says the pointer left every region, the balloon waits
 * this long before closing: the next mouse event may say it is still there.
 */
const POINTER_GONE_MS = 120;

const inTauri = "__TAURI_INTERNALS__" in window;

/** `pnpm dev:mock` with `?wander=fast`: strolls every few seconds, to watch them. */
function strollTiming(): StrollTiming {
  if (inTauri || new URLSearchParams(location.search).get("wander") !== "fast") {
    return DEFAULT_STROLLS;
  }
  return { ...DEFAULT_STROLLS, first: [2_000, 5_000], every: [8_000, 14_000], gap: [1_000, 3_000] };
}

async function start(): Promise<void> {
  const canvas = document.getElementById("overlay") as HTMLCanvasElement;
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("no 2D canvas");

  // Clawd, generated by scripts/gen-buddy-atlas.mjs; fails loudly if an animation is missing.
  const atlas = parseAtlas(atlasJson);
  requireClips(atlas, OVERLAY_CLIPS);
  const image = new Image();
  image.src = atlasUrl;
  await image.decode();

  // Scale and reduce motion come from the settings (applied live).
  const config = inTauri ? await getConfig().catch(() => DEFAULT_CONFIG) : DEFAULT_CONFIG;
  let buddyScale = config.scale;
  const scene = new Scene(atlas, { reduceMotion: config.reduceMotion, strolls: strollTiming() });
  // In the browser (`pnpm dev:mock`) there is no backend to tell.
  const sync = new HitRegionSync(inTauri ? setHitRegions : async () => {});

  /** The overlay as the backend last expanded it (throws, strolls). */
  let expanded: ExpandedLayout | null = null;
  /** How far the overlay was asked to grow, until it is asked to restore. */
  let room: ExpandMode | null = null;
  const canvasSize = () => ({ width: canvas.clientWidth, height: canvas.clientHeight });

  function viewport(): Viewport {
    const dpr = window.devicePixelRatio || 1;
    const width = Math.round(canvas.clientWidth * dpr);
    const height = Math.round(canvas.clientHeight * dpr);
    if (canvas.width !== width || canvas.height !== height) {
      canvas.width = width;
      canvas.height = height;
    }
    const home = homeArea(canvasSize(), expanded);
    return {
      width,
      height,
      devicePixelRatio: dpr,
      scale: buddyScale,
      home: {
        x: Math.round(home.x * dpr),
        y: Math.round(home.y * dpr),
        width: Math.round(home.width * dpr),
        height: Math.round(home.height * dpr),
      },
    };
  }

  /** A canvas point (CSS px) relative to the home area, where the scene's physics lives. */
  function toHome(x: number, y: number): { x: number; y: number } {
    const home = homeArea(canvasSize(), expanded);
    return { x: x - home.x, y: y - home.y };
  }

  /**
   * Grows the overlay while buddies are away from the corner and shrinks it
   * once all are back. The work area covers the floor strip, so a stroll
   * during a throw keeps the bigger one.
   */
  function syncRoom(): void {
    if (!inTauri) return;
    const need = scene.roomNeeded();
    if (need === room || (need === "floor" && room === "work")) return;
    room = need;
    if (need === null) {
      restoreOverlay().catch(() => {});
      return;
    }
    expandOverlay(need)
      .then((layout) => {
        if (!layout || room !== need) return;
        expanded = layout;
        scene.setWorkArea(flightArea(canvasSize(), layout));
        loop.invalidate();
      })
      .catch(() => {}); // Not expanded: buddies stay inside the corner area.
  }

  // The window fits the group plus room for the balloon above (or below)
  // it, so opening the balloon never resizes the window. Only real changes
  // are sent.
  let lastContentSize = "";
  function fitWindow(group: { width: number; height: number }): void {
    const width = Math.ceil(Math.max(group.width, BALLOON_MAX_WIDTH + 2 * buddyScale));
    const height = Math.ceil(group.height + BALLOON_MAX_HEIGHT + (TAIL_ROWS + 2) * buddyScale);
    const key = `${width}x${height}`;
    if (!inTauri || key === lastContentSize) return;
    lastContentSize = key;
    setOverlayContentSize(width, height).catch(() => {
      lastContentSize = "";
    });
  }

  const hover = new HoverState();
  /** The open balloon's rectangle in canvas pixels, for pointer tests. */
  let cardRect: Rect | null = null;
  let sprites: { id: string; x: number; y: number; size: number; mini?: { parent: string; stacked: boolean } }[] =
    [];

  /** Hidden from the tray: nothing is drawn and the loop sleeps. */
  let hiddenByUser = false;

  /** Clawd's (or a mini's) part of a sprite cell, in canvas pixels. */
  const bodyOf = (s: { x: number; y: number; size: number; mini?: unknown }): Rect => {
    const px = s.size / 32;
    const box = s.mini ? MINI_BOX : BODY_BOX;
    return {
      x: s.x + box.x * px,
      y: s.y + box.y * px,
      width: box.width * px,
      height: box.height * px,
    };
  };
  /** A buddy with the minis standing on its head: its balloon goes over them all. */
  const stackOf = (id: string, body: Rect): Rect => {
    const top = sprites
      .filter((s) => s.mini?.parent === id && s.mini.stacked)
      .reduce((y, s) => Math.min(y, bodyOf(s).y), body.y);
    return { ...body, y: top, height: body.y + body.height - top };
  };
  /** Clicks and drags on a mini act on its buddy. */
  const buddyOf = (id: string) => parseMiniKey(id)?.parent ?? id;

  const loop = new RenderLoop((now) => {
    // Hidden overlay: draw nothing and sleep until it is shown again.
    if (document.hidden || hiddenByUser) return null;
    const vp = viewport();
    const dpr = vp.devicePixelRatio;
    scene.setHovered(hover.hovered);
    const frame = scene.render(now, vp);
    sprites = frame.sprites;
    drawScene(ctx, image, frame);

    const regions: HitRegion[] = [...frame.regions];
    let next = frame.nextChangeAt;
    cardRect = null;
    const openId = hover.openId(now);
    const sprite =
      openId && !scene.isThrown(buddyOf(openId)) && frame.sprites.find((s) => s.id === openId);
    const mini = openId ? scene.miniView(openId) : undefined;
    const view = openId ? (mini?.parent ?? scene.view(openId)) : undefined;
    if (sprite && view) {
      const px = frame.pixel;
      const body = sprite.mini ? bodyOf(sprite) : stackOf(sprite.id, bodyOf(sprite));
      const lines = mini
        ? miniBalloonLines(mini.subagent, mini.parent, Date.now())
        : balloonLines(view, Date.now());
      const measured = measureBalloon(ctx, lines, dpr, px);
      const gap = (TAIL_ROWS + 1) * px;
      cardRect = placeCard(body, measured, vp, scene.currentCorner, gap);
      const up = !scene.currentCorner.startsWith("bottom");
      drawBalloon(ctx, cardRect, measured.lines, mini ? "working" : view.state, dpr, px, {
        x: body.x + body.width / 2,
        up,
      });
      // The balloon and its tail, down to the buddy, stay under the pointer.
      const top = up ? body.y + body.height : cardRect.y;
      const bottom = up ? cardRect.y + cardRect.height : body.y;
      regions.push({
        x: cardRect.x / dpr,
        y: Math.min(top, cardRect.y) / dpr,
        width: cardRect.width / dpr,
        height: (Math.max(bottom, cardRect.y + cardRect.height) - Math.min(top, cardRect.y)) / dpr,
      });
    }
    // The elapsed time is wall-clock based; express its start on this clock.
    const started = mini ? mini.subagent.since : view?.since;
    const since = started === undefined ? null : started - (Date.now() - now);
    const hoverNext = hover.nextChangeAt(now, since);
    if (hoverNext !== null) next = next === null ? hoverNext : Math.min(next, hoverNext);

    sync.update(regions);
    fitWindow(frame.contentSize);
    syncRoom();
    return next;
  });

  /** What the pointer is over: a buddy id, the balloon, or nothing. */
  function pointerTarget(x: number, y: number): string | null {
    const dpr = window.devicePixelRatio || 1;
    const [px, py] = [x * dpr, y * dpr];
    const inside = (r: Rect) => px >= r.x && py >= r.y && px < r.x + r.width && py < r.y + r.height;
    if (cardRect && inside(cardRect)) return "card";
    // The newest drawn on top wins.
    const sprite = [...sprites].reverse().find((s) => inside(bodyOf(s)));
    return sprite?.id ?? null;
  }

  // Hovering the +N chip shows everyone; leaving the group collapses it again.
  let collapseTimer: ReturnType<typeof setTimeout> | null = null;

  // Press on a buddy: a click if it stays put, a drag once it moves.
  let press: { id: string; x: number; y: number } | null = null;
  let dragging = false;
  canvas.addEventListener("pointerdown", (event) => {
    const id = pointerTarget(event.offsetX, event.offsetY);
    if (event.button !== 0 || id === null || id === "card") return;
    press = { id, x: event.offsetX, y: event.offsetY };
    canvas.setPointerCapture(event.pointerId);
  });

  function startDrag(id: string, from: { x: number; y: number }, now: number): void {
    if (!scene.grab(buddyOf(id), toHome(from.x, from.y), now)) return;
    dragging = true;
    hover.pointer(null, now);
    // Until the overlay has grown to the work area, the buddy flies inside
    // the window it has now (the browser page is the work area already).
    scene.setWorkArea(flightArea(canvasSize(), activeLayout(canvasSize(), expanded)));
    syncRoom();
  }

  // In the browser the page sees the pointer leave; in the app the overlay
  // turns click-through first, so the backend says when it left.
  let goneTimer: ReturnType<typeof setTimeout> | null = null;
  const stillHere = () => {
    if (goneTimer !== null) clearTimeout(goneTimer);
    goneTimer = null;
  };
  const pointerGone = () => {
    stillHere();
    hover.pointer(null, performance.now());
    loop.invalidate();
  };

  canvas.addEventListener("pointermove", (event) => {
    stillHere();
    const now = performance.now();
    if (press && !dragging) {
      const moved = Math.hypot(event.offsetX - press.x, event.offsetY - press.y);
      if (moved > DRAG_THRESHOLD) startDrag(press.id, press, now);
    }
    if (dragging) {
      scene.drag(toHome(event.offsetX, event.offsetY), now);
      loop.invalidate();
      return;
    }
    hover.pointer(pointerTarget(event.offsetX, event.offsetY), now);
    loop.invalidate();
    if (collapseTimer !== null) clearTimeout(collapseTimer);
    if (scene.chipContains(event.offsetX, event.offsetY)) {
      scene.setExpanded(true);
      loop.invalidate();
    }
    collapseTimer = setTimeout(() => {
      scene.setExpanded(false);
      loop.invalidate();
    }, COLLAPSE_AFTER_MS);
  });

  // Let go: throw what was dragged, or treat it as a click.
  const endPress = (event: PointerEvent, cancelled: boolean) => {
    const pressed = press;
    const wasDragging = dragging;
    press = null;
    dragging = false;
    if (wasDragging) {
      scene.release(performance.now());
      loop.invalidate();
    } else if (pressed && !cancelled) {
      click(pressed.id, event);
    }
  };
  canvas.addEventListener("pointerup", (event) => endPress(event, false));
  canvas.addEventListener("pointercancel", (event) => endPress(event, true));

  // Click on a buddy: focus its terminal; it hops when that worked. The
  // browser mock has no terminals, so it always hops.
  function click(target: string, event: PointerEvent): void {
    if (pointerTarget(event.offsetX, event.offsetY) !== target) return;
    const id = buddyOf(target);
    const focused = inTauri ? focusSession(id) : Promise.resolve(true);
    focused
      .then((ok) => {
        if (!ok) return;
        scene.hop(id, performance.now());
        loop.invalidate();
      })
      .catch(() => {}); // Best effort: nothing to show when focus fails.
  }

  canvas.addEventListener("pointerleave", pointerGone);

  if (inTauri) {
    await onOverlayPointer((pointer) => {
      if (!pointer.inside) {
        if (goneTimer === null) goneTimer = setTimeout(pointerGone, POINTER_GONE_MS);
        return;
      }
      stillHere();
      // The page may not see a mouse event until the pointer moves again.
      if (pointer.x !== null && pointer.y !== null && !dragging) {
        hover.pointer(pointerTarget(pointer.x, pointer.y), performance.now());
        loop.invalidate();
      }
    });
    await onConfigChanged((changed) => {
      buddyScale = changed.scale;
      scene.setReduceMotion(changed.reduceMotion, performance.now());
      loop.invalidate();
    });
    await onOverlayVisible((visible) => {
      hiddenByUser = !visible;
      if (!visible) {
        hover.pointer(null, performance.now());
        ctx.clearRect(0, 0, canvas.width, canvas.height);
      }
      loop.invalidate();
    });
    scene.setCorner((await getOverlayAnchor()).corner);
    await onOverlayAnchor((anchor) => {
      scene.setCorner(anchor.corner);
      loop.invalidate();
    });
  }

  await subscribeSessions({
    snapshot: (views) => {
      scene.setSessions(views, performance.now());
      loop.invalidate();
    },
    update: (view) => {
      scene.update(view, performance.now());
      loop.invalidate();
    },
    remove: (id) => {
      scene.remove(id, performance.now());
      loop.invalidate();
    },
    interaction: (from, to) => {
      scene.interact(from, to, performance.now());
      loop.invalidate();
    },
  });
  window.addEventListener("resize", () => loop.invalidate());
  document.addEventListener("visibilitychange", () => loop.invalidate());
  loop.invalidate();
}

start().catch((error) => console.error("claude-buddy overlay:", error));
